#!/usr/bin/env bash
set -e

# ===================================================================
# Linux / Ubuntu: MES 全栈容器安全停止脚本
# ===================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${SCRIPT_DIR}"

echo "==================================================================="
echo "[MES 停止工具] 正在安全停止 MES 容器集群并保留持久化数据..."
echo "==================================================================="

docker compose down

echo "==================================================================="
echo "[成功] MES 系统集群已安全停止 (数据依然持久化保存在本地目录中)。"
echo "==================================================================="
