#!/usr/bin/env bash
set -e

# ===================================================================
# Linux / Ubuntu: MES 全栈容器一键启动脚本
# ===================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${SCRIPT_DIR}"

echo "==================================================================="
echo "[MES 启动工具] 正在拉起 MES 全套容器集群 (MySQL, Redis, 后端, 前端)..."
echo "==================================================================="

if [ ! -f ".env" ]; then
    if [ -f ".env.example" ]; then
        echo "[提示] 未检测到 .env 配置文件，正在根据 .env.example 自动生成..."
        cp .env.example .env
    fi
fi

echo "[执行] 正在启动所有容器服务..."
docker compose up -d

echo "==================================================================="
echo "[成功] MES 系统集群已全部后台启动！"
echo ""
echo "系统服务访问入口："
echo "  - 前端 Web 访问地址 ： http://<服务器IP>:1228"
echo "  - 后端 API 接口地址 ： http://<服务器IP>:48080/admin-api/"
echo "  - MySQL 数据库端口  ： 3306 (账号: root, 密码详见 .env)"
echo "  - Redis 缓存端口    ： 6379"
echo "==================================================================="
